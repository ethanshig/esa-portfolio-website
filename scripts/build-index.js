  console.log(`built index.html: ${built.plates.length} Plates (${real} real, ${built.plates.length - real} placeholders), ${built.records.length} Records in JSON-LD, seed ${built.field.plates[built.field.seed].id}, mean neighbour similarity ${built.field.meanEdge.toFixed(3)}`);
