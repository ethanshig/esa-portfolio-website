#!/usr/bin/env bun
/**
 * Writes index.html: the index as a sheet of Plates (issue #17).
 *
 *   data/plates.js                        the Plates, their Facets and their Records
 *   js/index-sheet/field.js               the growth (the same code the browser runs)
 *   adventure/content/world.json          each Drawing's alt text, by image path
 *   api/adventure/portfolio.public.json   each Record's title, line and dates, for JSON-LD
 *   images/plates/<model>.png             each model Plate's still for the no-JS index
 *                                         (scripts/render-model-stills.js makes them)
 *
 * and writes data/plate-shapes.js too: every Plate's m x n modules (js/index-sheet/shape.js),
 * computed from each drawing's measured pixel size, so the browser grows the field without
 * measuring an image. Run it again whenever an image or the data changes.
 *
 * The scraper contract holds here as on the project pages: every word a reader can see is
 * in this HTML, and JavaScript adds no text. Without JavaScript or WebGL the Plates are a
 * plain grid of links in growth order; js/index-sheet/index-sheet.js upgrades it to the sheet.
 *
 * This script writes no prose. The two sentences in the meta description are story-layer's
 * landing statement and intro line, verbatim (#13); Plate titles and meta are the data's.
 *
 * Run: bun scripts/build-index.js        (fails loudly on any gap in the data)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as DATA from '../data/plates.js';
import { growField } from '../js/index-sheet/field.js';
import { shapeForImage, shapeForHint, boxSteps, keepOf, SPAN_MIN, SPAN_MAX } from '../js/index-sheet/shape.js';
import { imageSize } from './image-size.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const PX_PER_STEP = 20;

/* #13: they leave the index's body and become its meta description, verbatim */
const STATEMENT = 'Architecture, sustainability, and ecological resilience.';
const INTRO = 'I study Sustainable Design at the University of Illinois. My work sits where built environments meet natural systems.';

export const esc = (s) => String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
export const stillPath = (model) => `images/plates/${model}.png`;

function load() {
  const world = JSON.parse(readFileSync(join(root, 'adventure/content/world.json'), 'utf8'));
  const { projects } = JSON.parse(readFileSync(join(root, 'api/adventure/portfolio.public.json'), 'utf8'));
  return { world, projects };
}

/* Every Plate's shape: a drawing's from its measured image, a model's or placeholder's from its hint.
   Drawings also carry px and keep (the share of the image the box shows), for checking. */
export function computeShapes() {
  const shapes = {};
  for (const p of DATA.PLATES) {
    if (p.drawing) {
      const file = join(root, p.drawing);
      if (!existsSync(file)) throw new Error(`build-index: plate ${p.id}: ${p.drawing} does not exist`);
      const { w, h } = imageSize(file);
      let { m, n, keep } = shapeForImage(w, h, p.size);
      if (p.shape) {                                    /* Ethan's override of the rule, for this Plate only */
        [m, n] = p.shape;
        if (![m, n].every((k) => Number.isInteger(k) && k >= SPAN_MIN && k <= SPAN_MAX)) throw new Error(`build-index: plate ${p.id}: shape ${p.shape} is not two whole spans in ${SPAN_MIN}..${SPAN_MAX}`);
        const [bw, bh] = boxSteps(m, n);
        keep = keepOf(w / h, bw / bh);
      }
      shapes[p.id] = { m, n, px: [w, h], keep: Number(keep.toFixed(4)) };
    } else {
      shapes[p.id] = shapeForHint(p.size, { placeholder: !DATA.RECORDS[p.record].href });
    }
  }
  return shapes;
}

export function renderShapes(shapes) {
  return `/* Generated by scripts/build-index.js. Do not edit by hand: change data/plates.js or the images
   and rerun it. Each Plate's shape in 16-step modules (js/index-sheet/shape.js): m across, n down.
   A drawing's comes from its image's pixel size (px); keep is the share of the image its
   cover-fit box shows. A model's or placeholder's comes from its size hint. */
export const SHAPES = {
${Object.entries(shapes).map(([id, v]) => `  ${JSON.stringify(id)}: ${JSON.stringify(v)},`).join('\n')}
};
`;
}

/* Everything the page needs, checked against the files it points at. Throws on the first gap. */
export function plan({ world, projects }) {
  const SHAPES = computeShapes();
  const field = growField({ ...DATA, SHAPES });
  const altBySrc = new Map(Object.values(world.media).map((m) => [m.src, m.alt]));
  const recordFor = (href) => projects.find((p) => `projects/${p.id}.html` === href) || null;
  const fail = (msg) => { throw new Error(`build-index: ${msg}`); };

  for (const [id, r] of Object.entries(DATA.RECORDS)) {
    if (!r.href) continue;
    if (!existsSync(join(root, r.href))) fail(`record ${id}: ${r.href} does not exist`);
    const rec = recordFor(r.href);
    if (!rec) fail(`record ${id}: ${r.href} is not an approved record in portfolio.public.json`);
    const want = rec.dates || null;
    if (JSON.stringify(r.dates) !== JSON.stringify(want)) fail(`record ${id}: dates ${JSON.stringify(r.dates)} differ from the record's ${JSON.stringify(want)}`);
    for (const d of r.drawings) if (!existsSync(join(root, d))) fail(`record ${id}: drawing ${d} does not exist`);
  }
  const plates = field.order.map((i) => field.plates[i]).map((p) => {
    const r = DATA.RECORDS[p.record];
    if (p.placeholder) return { p, r };
    let src, alt;
    if (p.drawing) {
      if (!existsSync(join(root, p.drawing))) fail(`plate ${p.id}: ${p.drawing} does not exist`);
      if (!altBySrc.has(p.drawing)) fail(`plate ${p.id}: ${p.drawing} has no alt text in world.json`);
      src = p.drawing; alt = altBySrc.get(p.drawing);
    } else {
      src = stillPath(p.model);
      if (!existsSync(join(root, `models/${p.model}.glb`))) fail(`plate ${p.id}: models/${p.model}.glb does not exist`);
      if (!existsSync(join(root, src))) fail(`plate ${p.id}: ${src} does not exist (run scripts/render-model-stills.js)`);
      alt = p.alt || '';
    }
    return { p, r, src, alt };
  });
  const records = field.records.filter((x) => DATA.RECORDS[x.id].href).map((x) => {
    const r = DATA.RECORDS[x.id];
    const rec = recordFor(r.href);
    const firstDrawing = plates.find((e) => e.p.record === x.id && e.p.drawing);
    return { r, rec, image: firstDrawing ? { src: firstDrawing.src, alt: firstDrawing.alt } : null };
  });
  return { field, plates, records, SHAPES };
}

function plateItem({ p, r, src, alt }) {
  const cls = `ix-m${p.m} ix-n${p.n}`;
  const words = `<span class="ix-name">${esc(r.title)}</span> <span class="ix-meta">· ${esc(r.meta)}</span>`;
  if (p.placeholder) {
    return `<li class="${cls}"><span class="env-title ix-plate ix-placeholder" data-plate="${esc(p.id)}">${words}</span></li>`;
  }
  const [w, h] = [p.wSteps * PX_PER_STEP, p.hSteps * PX_PER_STEP];
  const still = p.model ? ' class="ix-still"' : '';
  return `<li class="${cls}"><a class="env-title ix-plate" href="${esc(r.href)}" data-drawing="${esc(p.id)}">` +
    `<img${still} src="${esc(src)}" alt="${esc(alt)}" width="${w}" height="${h}" loading="lazy" decoding="async">${words}</a></li>`;
}

function jsonLd(records) {
  const ld = {
    '@context': 'https://schema.org',
    '@type': 'ItemList',
    itemListOrder: 'https://schema.org/ItemListUnordered',
    numberOfItems: records.length,
    itemListElement: records.map(({ r, rec, image }, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      url: r.href,
      item: {
        '@type': 'CreativeWork',
        name: rec.title,
        description: rec.oneLine,
        url: r.href,
        creator: { '@type': 'Person', name: 'Ethan Shig Anderson' },
        dateCreated: (rec.dates && rec.dates.start) || undefined,
        temporalCoverage: rec.dates && rec.dates.start && rec.dates.end ? `${rec.dates.start}/${rec.dates.end}` : undefined,
        sourceOrganization: rec.context && rec.context.institution ? { '@type': 'Organization', name: rec.context.institution } : undefined,
        image: image ? { '@type': 'ImageObject', contentUrl: image.src, description: image.alt } : undefined,
      },
    })),
  };
  /* "</" would close the script element early */
  return JSON.stringify(ld, (k, v) => (v === undefined ? undefined : v), 2).replace(/<\//g, '<\\/');
}

